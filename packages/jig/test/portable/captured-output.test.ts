async function fixture(work: (root: string, fd: number) => Promise<void>) {
  const root = await realpath(await mkdtemp(join(tmpdir(), 'jig-output-capture-')))
  const fd = privateOpenFileRoot(root)
  try {
    await work(root, fd)
  } finally {
    closeSync(fd)
    await rm(root, { recursive: true, force: true })
  }
}

test('retained export reseals bounded verified bytes and complete directory evidence', () => {
  const bytes = Buffer.from([0, 255, 128])
  const snapshot = capturePrivateRetainedOutput({
    files: [{ path: 'nested/binary', bytes, digest: sha256(bytes) }],
    directories: ['nested', 'empty'],
  })
  try {
    bytes.fill(0)
    expect(snapshot.directories).toEqual(['empty', 'nested'])
    expect([...readPrivateCapturedOutput(snapshot)[0]!.contents]).toEqual([0, 255, 128])
    expect(() => requirePrivateCapturedOutput({ ...snapshot })).toThrow('not authentic')
  } finally {
    snapshot.close()
  }
  for (const input of [
    { files: [{ path: 'a', bytes, digest: sha256(Buffer.from('wrong')) }], directories: [] },
    { files: [{ path: 'nested/a', bytes, digest: sha256(bytes) }], directories: [] },
    { files: [{ path: 'a', bytes, digest: sha256(bytes) }], directories: ['a'] },
    { files: [], directories: ['a', 'a'] },
    {
      files: Array.from({ length: 65 }, (_, i) => ({
        path: `f-${i}`,
        bytes,
        digest: sha256(bytes),
      })),
      directories: [],
    },
  ])
    expect(() => capturePrivateRetainedOutput(input)).toThrow()
  const large = Buffer.alloc(16 * 1024 * 1024 + 1)
  expect(() =>
    capturePrivateRetainedOutput({
      files: [{ path: 'large', bytes: large, digest: sha256(large) }],
      directories: [],
    }),
  ).toThrow(PrivateOutputProfileError)
})

test('artifact manifest identity binds paths and empty directories, not only backing bytes', async () =>
  fixture(async (root, fd) => {
    await writeFile(join(root, 'first'), 'same')
    const first = capturePrivateOutput(fd)
    await rm(join(root, 'first'))
    await writeFile(join(root, 'second'), 'same')
    const second = capturePrivateOutput(fd)
    await mkdir(join(root, 'empty'))
    const third = capturePrivateOutput(fd)
    try {
      expect(first.digest).toBe(second.digest)
      expect(privateCapturedOutputManifestDigest(first)).not.toBe(
        privateCapturedOutputManifestDigest(second),
      )
      expect(privateCapturedOutputManifestDigest(second)).not.toBe(
        privateCapturedOutputManifestDigest(third),
      )
      expect(() => privateCapturedOutputManifestDigest({ ...first })).toThrow('not authentic')
    } finally {
      first.close()
      second.close()
      third.close()
    }
  }))

test('artifact composition streams prefixed files and empty directories, rejecting collisions', async () =>
  fixture(async (root, fd) => {
    await mkdir(join(root, 'empty'))
    await writeFile(join(root, 'binary'), Buffer.from([0, 255, 128]))
    const source = capturePrivateOutput(fd)
    const composed = capturePrivateOutputComposition([
      { snapshot: source, prefix: 'copies' },
      { snapshot: source, prefix: 'overview' },
    ])
    try {
      expect(composed.files.map((file) => file.path)).toEqual(['copies/binary', 'overview/binary'])
      expect(composed.directories).toEqual(['copies', 'copies/empty', 'overview', 'overview/empty'])
      expect([...readPrivateCapturedOutput(composed)[1]!.contents]).toEqual([0, 255, 128])
      expect(() =>
        capturePrivateOutputComposition([
          { snapshot: source, prefix: 'same' },
          { snapshot: source, prefix: 'same' },
        ]),
      ).toThrow('collide')
      expect(() => capturePrivateOutputComposition([{ snapshot: { ...source } }])).toThrow(
        'not authentic',
      )
      expect(() =>
        capturePrivateOutputComposition([{ snapshot: source, prefix: '../escape' }]),
      ).toThrow()
      source.close()
      expect([...readPrivateCapturedOutput(composed)[0]!.contents]).toEqual([0, 255, 128])
    } finally {
      source.close()
      composed.close()
    }
  }))

test('phase output selection preserves generated bytes but replaces complete fresh reports roots', async () =>
  fixture(async (root, fd) => {
    await mkdir(join(root, 'generated'))
    await mkdir(join(root, 'reports'))
    await writeFile(join(root, 'generated/parser.ts'), 'generated')
    await writeFile(join(root, 'reports/generate.txt'), 'generator report')
    const generated = capturePrivateOutput(fd)
    await rm(join(root, 'generated'), { recursive: true })
    await rm(join(root, 'reports/generate.txt'))
    const tested = capturePrivateOutput(fd)
    const selected = capturePrivateOutputSelection([generated, tested], ['generated', 'reports'])
    try {
      generated.close()
      tested.close()
      expect(readPrivateCapturedOutput(selected).map((file) => file.path)).toEqual([
        'generated/parser.ts',
      ])
      expect(selected.directories).toEqual(['generated', 'reports'])
      expect(readPrivateCapturedOutput(selected)[0]!.contents.toString()).toBe('generated')
      expect(() => capturePrivateOutputSelection([{ ...selected }], ['generated'])).toThrow()
    } finally {
      generated.close()
      tested.close()
      selected.close()
    }
  }))

test('output capture preserves bytes and empty directory evidence after the source disappears', async () =>
  fixture(async (root, fd) => {
    await mkdir(join(root, 'empty'))
    await mkdir(join(root, 'nested'))
    await writeFile(join(root, 'nested/binary'), Buffer.from([0, 255, 128]))
    await writeFile(join(root, 'zero'), '')
    const captured = capturePrivateOutput(fd)
    try {
      expect(captured.directories).toEqual(['empty', 'nested'])
      expect(
        captured.files.map((file) => ({ path: file.path, offset: file.offset, bytes: file.bytes })),
      ).toEqual([
        { path: 'nested/binary', offset: 0, bytes: 3 },
        { path: 'zero', offset: 3, bytes: 0 },
      ])
      await rm(join(root, 'nested'), { recursive: true })
      await writeFile(join(root, 'zero'), 'changed')
      const files = readPrivateCapturedOutput(captured)
      expect([...files[0]!.contents]).toEqual([0, 255, 128])
      expect(files[1]!.contents.length).toBe(0)
      files[0]!.contents.fill(7)
      expect([...readPrivateCapturedOutput(captured)[0]!.contents]).toEqual([0, 255, 128])
      expect(() =>
        writeSync(requirePrivateCapturedOutput(captured).fd, Buffer.from('bad')),
      ).toThrow()
      expect(() => requirePrivateCapturedOutput({ ...captured })).toThrow('not authentic')
      expect(() => requirePrivateCapturedOutput(JSON.parse(JSON.stringify(captured)))).toThrow(
        'not authentic',
      )
    } finally {
      captured.close()
    }
    expect(() => readPrivateCapturedOutput(captured)).toThrow('not active')
    captured.close()
  }))
test('output and invocation captures have separate authority and byte bounds', async () =>
  fixture(async (root, fd) => {
    const bytes = Buffer.alloc(8 * 1024 * 1024 + 1, 42)
    expect(() => capturePrivateInput(bytes)).toThrow('byte limit')
    const output = capturePrivateBytes(bytes, 'output')
    try {
      expect(() => requirePrivateCapturedInput(output as any)).toThrow('purpose')
    } finally {
      output.close()
    }
    await writeFile(join(root, 'large'), bytes)
    const captured = capturePrivateOutput(fd)
    try {
      expect(readPrivateCapturedOutput(captured)[0]!.contents.equals(bytes)).toBe(true)
      const file = captured.files[0]!
      expect(() => capturePrivateArtifactInput(captured, { ...file })).toThrow('original')
      const input = capturePrivateArtifactInput(captured, file)
      try {
        expect(input.purpose).toBe('artifact-input')
        expect(requirePrivateCapturedInput(input).bytes).toBe(bytes.length)
        expect(readPrivateCapturedInput(input).equals(bytes)).toBe(true)
      } finally {
        input.close()
      }
      const cancelled = new AbortController()
      cancelled.abort()
      expect(() => capturePrivateArtifactInput(captured, file, cancelled.signal)).toThrow()
    } finally {
      captured.close()
    }
    await writeFile(join(root, 'excess'), Buffer.alloc(8 * 1024 * 1024))
    expect(() => capturePrivateOutput(fd)).toThrow(PrivateOutputProfileError)
  }))
test('output capture refuses links, protected names, excess entries and cancellation', async () =>
  fixture(async (root, fd) => {
    await writeFile(join(root, 'original'), 'bytes')
    await symlink('original', join(root, 'alias'))
    expect(() => capturePrivateOutput(fd)).toThrow(PrivateOutputProfileError)
    await rm(join(root, 'alias'))
    await link(join(root, 'original'), join(root, 'hard'))
    expect(() => capturePrivateOutput(fd)).toThrow(PrivateOutputProfileError)
    await rm(join(root, 'hard'))
    await mkdir(join(root, '.jig'))
    expect(() => capturePrivateOutput(fd)).toThrow(PrivateOutputProfileError)
    await rmdir(join(root, '.jig'))
    for (let index = 0; index < 65; index++) await writeFile(join(root, `file-${index}`), '')
    expect(() => capturePrivateOutput(fd)).toThrow('finite file profile')
    const cancellation = new AbortController()
    cancellation.abort()
    expect(() => capturePrivateOutput(fd, cancellation.signal)).toThrow()
  }))
