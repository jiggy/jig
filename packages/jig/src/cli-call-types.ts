import { asciiJsonString } from './cli-usage.js'
import { invalid } from './diagnostics.js'
import type { InvocationOperationDescriptor } from './invocation-contract.js'
import type { JsonObject, JsonScalar, JsonValue } from './json.js'
import { captureFlowSource } from './project/flow-source.js'
import { isProtectedProjectPath } from './project/paths.js'

const MAX_DECLARATION_LENGTH = 256 * 1024
const MAX_PROJECTION_DEPTH = 12
const MAX_RESULT_ALTERNATIVES = 32

/** Project one checked package. No authored module is loaded. */
export async function generateCallTypes(
  project: string,
  path: string,
  signal?: AbortSignal,
): Promise<string> {
  signal?.throwIfAborted()
  if (path.split('/').some(isProtectedProjectPath))
    invalid('PROJECT_SOURCE_PROTECTED', 'Select a Flow package outside protected .jig state')
  const source = await captureFlowSource(project, { kind: 'members', paths: [path] })
  try {
    const inspected = source.members[0]?.inspected
    if (inspected?.entrypoint.path !== 'FLOW.ts')
      invalid('TYPES_ENTRYPOINT', 'Select a package with a FLOW.ts entrypoint', path)

    const header = '// Generated by jig types from the captured Flow package.\n'
    const slots = Object.keys(inspected.metadata.uses ?? {}).sort()
    const settings = projectObjectSchema(object(inspected.schemas.settings?.schema))
    const hasCalls = slots.length > 0
    if (!hasCalls && settings === 'JsonObject')
      return `${header}export type { RunContext } from '@jigging/flow'\n`

    const contracts = new Map(inspected.usedContracts.map(({ slot, contract }) => [slot, contract]))
    const lines = [
      header.trimEnd(),
      hasCalls
        ? "import type { CallOptions, CallResult, FlowCall, JsonObject, JsonValue, RunContext as FlowRunContext } from '@jigging/flow'"
        : "import type { JsonObject, JsonValue, RunContext as FlowRunContext } from '@jigging/flow'",
      '',
    ]
    const footer: string[] = []
    // Infer the slot directly, then check that the slot and input belong to the same request.
    if (hasCalls) {
      lines.push('interface ChildCalls {')
      footer.push(
        '}',
        '',
        'type ChildCallRequest<Slot extends keyof ChildCalls> = {',
        "  [Name in Slot]: { readonly slot: Name; readonly input: ChildCalls[Name]['input'] }",
        '}[Slot]',
        '',
        "export interface RunContext extends Omit<FlowRunContext, 'call'> {",
        '  call<Slot extends keyof ChildCalls>(',
        '    request: FlowCall & { readonly slot: Slot } & ChildCallRequest<Slot>,',
        '    options?: CallOptions,',
        "  ): Promise<ChildCalls[Slot]['result']>",
      )
    } else {
      footer.push('export interface RunContext extends FlowRunContext {')
    }
    if (settings !== 'JsonObject') footer.push(`  readonly settings: ${settings}`)
    footer.push('}', '')

    let length = lines.join('\n').length + 1 + footer.join('\n').length
    for (const slot of slots) {
      signal?.throwIfAborted()
      if (length > MAX_DECLARATION_LENGTH) break
      const operation = contracts.get(slot)?.invocation
      const input =
        operation?.input === undefined ? "FlowCall['input']" : projectSchema(operation.input)
      const result = operation === undefined ? 'CallResult' : projectCallResult(operation)
      const entry = [
        `  ${asciiJsonString(slot)}: {`,
        `    input: ${input}`,
        `    result: ${result}`,
        '  }',
      ].join('\n')
      length += entry.length + 1
      lines.push(entry)
    }
    if (length > MAX_DECLARATION_LENGTH)
      invalid('TYPES_LIMIT', 'The declaration exceeds 256 KiB. Use the FLOW SDK RunContext', path)
    return [...lines, ...footer].join('\n')
  } finally {
    await source.dispose()
  }
}

function projectCallResult(operation: InvocationOperationDescriptor): string {
  // The package result gate admits done and the named outcomes. Artifact handles
  // travel separately from the JSON envelope that the schema validates.
  const outcomes = ['done', ...Object.keys(operation.outcomes ?? {}).sort()]
  const tags = outcomes.map((name) => `{ readonly outcome: ${asciiJsonString(name)} }`)
  const result = object(operation.result)
  const alternatives = result?.anyOf ?? result?.oneOf
  const branches =
    Array.isArray(alternatives) && alternatives.length <= MAX_RESULT_ALTERNATIVES
      ? alternatives
      : [result]
  const shapes = new Set<string>()
  for (const branch of branches) {
    const properties = object(object(branch)?.properties)
    const outcome = projectSchema(properties?.outcome)
    const output = projectSchema(properties?.output)
    if (outcome === 'JsonValue' && output === 'JsonValue') {
      // A branch with no projected fields contributes the entire SDK shape.
      shapes.clear()
      break
    }
    shapes.add(`{ readonly outcome: ${outcome}; readonly output: ${output} }`)
  }
  const payload = shapes.size === 0 ? '' : ` & (${[...shapes].join(' | ')})`
  return `CallResult & (${tags.join(' | ')})${payload}`
}

/** Describe structural supersets using only independent positive constraints. */
function projectSchema(value: JsonValue | undefined, depth = 0): string {
  if (depth >= MAX_PROJECTION_DEPTH) return 'JsonValue'
  if (value === false) return 'never'
  const schema = object(value)
  if (schema === undefined) return 'JsonValue'
  if (scalar(schema.const)) return literal(schema.const)
  if (Array.isArray(schema.enum) && schema.enum.every(scalar))
    return schema.enum.map(literal).join(' | ')
  switch (schema.type) {
    case 'string':
    case 'boolean':
    case 'null':
    case 'number':
      return schema.type
    case 'integer':
      return 'number'
    case 'array':
      return schema.prefixItems === undefined
        ? `readonly (${projectSchema(schema.items, depth + 1)})[]`
        : 'readonly JsonValue[]'
    case 'object':
      return projectObjectSchema(schema, depth)
    default:
      return 'JsonValue'
  }
}

function projectObjectSchema(schema: JsonObject | undefined, depth = 0): string {
  const properties = object(schema?.properties)
  const required = new Set(Array.isArray(schema?.required) ? schema.required.map(String) : [])
  const names = new Set([...Object.keys(properties ?? {}), ...required])
  const fields = [...names].sort().map((name) => {
    const optional = required.has(name) ? '' : '?'
    return `readonly ${asciiJsonString(name)}${optional}: ${projectSchema(properties?.[name], depth + 1)}`
  })
  return fields.length === 0 ? 'JsonObject' : `JsonObject & { ${fields.join('; ')} }`
}

function object(value: JsonValue | undefined): JsonObject | undefined {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? (value as JsonObject)
    : undefined
}

function scalar(value: JsonValue | undefined): value is JsonScalar {
  return value === null || ['boolean', 'number', 'string'].includes(typeof value)
}

function literal(value: JsonScalar): string {
  return typeof value === 'string' ? asciiJsonString(value) : String(value)
}
